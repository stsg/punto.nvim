local punto = require("punto")
local config = require("punto.config")
local H = require("tests.helpers")

local function setup(extra)
  config.reset()
  local opts = vim.tbl_extend("force", {
    layout = "ru(winkeys)",
    keymap = false,
    notify = false,
  }, extra or {})
  return punto.setup(opts)
end

local function command()
  vim.cmd("PuntoSwitch")
end

T.test("defaults use ru(phonetic_winkeys) and <Leader>sw", function()
  config.reset()
  local cfg = config.get()
  T.eq("ru(phonetic_winkeys)", cfg.layout)
  T.eq("en(qwerty)", cfg.latin_layout)
  T.eq("auto", cfg.direction)
  T.eq("<Leader>sw", cfg.keymap.normal)
  T.eq("<Leader>sw", cfg.keymap.visual)
end)

T.test("default setup uses ru(phonetic_winkeys)", function()
  config.reset()
  punto.setup({ keymap = false, notify = false })
  H.buf({ "priwet" })
  H.cursor(1, 5)
  command()
  T.eq({ "привет" }, H.lines())
end)

T.test("normal mode converts the last word", function()
  setup()
  H.buf({ "ghbdtn" })
  H.cursor(1, 5)
  command()
  T.eq({ "привет" }, H.lines())
end)

T.test("normal mode handles auto direction", function()
  setup()
  H.buf({ "привет" })
  H.cursor(1, 0)
  command()
  T.eq({ "ghbdtn" }, H.lines())
end)

T.test("normal mode respects an explicit direction argument", function()
  setup()
  H.buf({ "ghbdtn" })
  H.cursor(1, 5)
  vim.cmd("PuntoSwitch to_en")
  T.eq({ "ghbdtn" }, H.lines())

  H.buf({ "привет" })
  H.cursor(1, 0)
  vim.cmd("PuntoSwitch to_en")
  T.eq({ "ghbdtn" }, H.lines())
end)

T.test("word scope leaves trailing punctuation", function()
  setup()
  H.buf({ "ghbdtn?" })
  H.cursor(1, 6)
  command()
  T.eq({ "привет?" }, H.lines())
end)

T.test("token scope converts trailing punctuation", function()
  setup({ normal_scope = "token" })
  H.buf({ "ghbdtn?" })
  H.cursor(1, 6)
  command()
  T.eq({ "привет," }, H.lines())
end)

T.test("visual command converts exactly the selection", function()
  setup()
  H.buf({ "ghbdtn test" })
  vim.cmd("normal! v")
  vim.cmd("normal! \27")
  vim.fn.setpos("'<", { 0, 1, 1, 0 })
  vim.fn.setpos("'>", { 0, 1, 6, 0 })
  vim.cmd("'<,'>PuntoSwitch")
  T.eq({ "привет test" }, H.lines())
end)

T.test("numeric range converts whole lines", function()
  setup()
  H.buf({ "ghbdtn", "test" })
  vim.cmd("1,2PuntoSwitch")
  T.eq({ "привет", "еуые" }, H.lines())
end)

T.test("no-op leaves the buffer unchanged", function()
  setup()
  H.buf({ "123" })
  H.cursor(1, 0)
  command()
  T.eq({ "123" }, H.lines())
end)

T.test("refuses a non-modifiable buffer", function()
  setup()
  H.buf({ "ghbdtn" })
  H.cursor(1, 5)
  vim.bo.modifiable = false
  command()
  T.eq({ "ghbdtn" }, H.lines())
  vim.bo.modifiable = true
end)

T.test("undo restores the file contents in one step", function()
  setup()
  local path = H.edit_file({ "ghbdtn" })
  H.cursor(1, 5)
  command()
  T.eq({ "привет" }, H.lines())

  vim.cmd("silent undo")
  T.eq({ "ghbdtn" }, H.lines())
  H.rm(path)
end)

T.test("unknown layout fails setup", function()
  config.reset()
  T.raises(function()
    punto.setup({ layout = "xx(nope)", keymap = false, notify = false })
  end, "unknown layout")
end)

T.test("setup is idempotent for keymaps", function()
  setup({ keymap = "<F5>" })
  T.ok(vim.fn.maparg("<F5>", "n") ~= "", "mapping should exist")

  setup({ keymap = false })
  T.eq("", vim.fn.maparg("<F5>", "n"), "mapping should be removed")
end)

T.test("public convert() works without a buffer", function()
  setup()
  local text, changed = punto.convert("ghbdtn", { direction = "to_ru" })
  T.eq("привет", text)
  T.eq(true, changed)

  text, changed = punto.convert("123", { direction = "to_ru" })
  T.eq("123", text)
  T.eq(false, changed)
end)
